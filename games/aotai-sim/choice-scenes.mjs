export function optionSceneFor(s,action){
 if(!action)return null;
 const [kind,id]=action.id.split(':'),base=sceneFor(s);
 let vignette;
 if(kind==='choice')vignette=CHOICE_SCENES[s.event]?.[id];
 else if(kind==='move'){
  const terrain=TRAVEL_DETAILS[s.node],target=NODE_BY_ID[action.target]?.name||'来路',returning=s.returning?'沿确认过的来路':'沿当前选定的路线';
  const details={
   steady:A(`在${terrain[0]}上保持节奏`,'trail',`你准备${returning}走向${target}，在${terrain[0]}上保持自己的步速。`,'不急着抢下一步，把力气留给整段路。',`${terrain[1]}还在前面，实际耗时、天气与负重会一路跟着你。`),
   fast:A(`加快通过${terrain[1]}`,'boots',`你准备收紧肩带，在${terrain[1]}上加快步频，向${target}赶路。`,'这一段想少花点时间，要多用一些体力。',`${terrain[2]}仍要判断，加速并不保证没有受伤或额外消耗。`),
   careful:A(`逐个确认${terrain[2]}`,'cairn',`你准备在${terrain[2]}前放慢速度，确认方向与支撑，再向${target}走。`,'先看清，再把下一步落下去。',`${terrain[0]}需要耐心，谨慎会让你在这段花更多时间。`)
  };vignette=details[id];
 }else if(kind==='use')vignette=ITEM_SCENES[id];
 else if(kind==='drop'&&ITEMS[id]){
  const item=ITEMS[id],last=s.inventory[id]===1;
  vignette=A(`从包里取出一件${item.name}`,`gear:${id}`,`你准备在${NODE_BY_ID[s.node].name}取出一件${item.name}，把它从随身储备里放弃。`,'少背一点，也要接受少一种后面的处理办法。',`这件重 ${item.weight} kg。${last?'这是背包里的最后一件；':'包里还留有同类物品；'}本分支丢弃后无法取回，只能在复盘中重选。`);
 }else vignette=UTILITY_SCENES[action.id];
 if(!vignette)throw new Error(`Missing option scene: ${s.event||s.node}/${action.id}`);
 vignette=structuredClone(vignette);
 // Past deadlines and equipment are real state; an intention must not invent a person or success.
 const expiredChoice=kind==='choice'&&s.event==='hiker'&&s.quest?.status==='failed';
 if(expiredChoice&&id==='report')vignette=A('把没有回应的位置带回去','gear:map','你准备记录石壁、空背包与已经错过的等待窗口，把这段消息报告出去。','把事实带回去，不能把过去的窗口说成仍然有效。','石槽里没有新的回应；之后的报告无法确认这次等待已经被挽回。');
 else if(expiredChoice){vignette.summary=`等待窗口已经错过。${vignette.summary.replace('你准备','此前可以')}`;vignette.voice='这份安排现在无法执行。只能在复盘中回到找到他之前，重选这一步。';vignette.detail=`原先的取舍：${vignette.detail}这段设想不能改写已经过去的窗口。`;}
 if(action.id==='refill'&&!s.inventory.filter)vignette.prop='gear:stove';
 if(action.id==='sos'&&!s.inventory.satellite)vignette.prop='radio';
 if(action.id==='wait'&&s.rescue)vignette.detail=`联络预计还需 ${Math.ceil(s.rescue.remaining)} 个游戏小时。这次等待仍可能受天气变化影响。`;
 const reply=expiredChoice?'':replyFor(s,action),dialogue=[
  {speaker:'现场',kind:'行动设想',text:vignette.summary},
  {speaker:'你',kind:base.actor?'拟回应':'拟行动',text:reply||vignette.voice},
  {speaker:'现场',kind:'尚未执行',text:vignette.detail}
 ];
 return {...base,background:vignette.background||base.background,prop:vignette.prop,title:vignette.title,caption:vignette.summary,summary:vignette.summary,dialogue,actionId:action.id,blocked:action.disabled||'',observations:[
  {title:'这一步的安排',text:`${action.title}。${action.desc}${action.disabled?` 当前条件：${action.disabled}。`:''}`,x:85,y:40},
  {title:'眼前的取舍',text:vignette.detail,x:68,y:72}
 ]};
}
